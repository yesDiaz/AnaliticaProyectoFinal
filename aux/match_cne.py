import pandas as pd, numpy as np
coef = pd.read_csv("/srv/mark02/analitica-final/entrega/coef_estaciones.csv")
ids = sorted(coef.STATION_ID.unique())
print(len(ids), ids[:5], ids[-3:])
cne = pd.read_csv("/srv/mark02/analitica-final/aux/cne.csv", dtype={"Codigo": str}, low_memory=False)
print("CNE:", cne.shape)
cne["cod_int"] = pd.to_numeric(cne.Codigo, errors="coerce")
m = cne[cne.cod_int.isin(ids)].copy()
print("match:", m.cod_int.nunique(), "de", len(ids))
falt = sorted(set(ids) - set(m.cod_int.dropna().astype("int64")))
print("faltan:", len(falt), falt[:10])
print(m[["Codigo", "Nombre", "Departamento", "Altitud", "LONGITUD", "LATITUD", "Zona Hidrografica"]].head(5).to_string())
print(m.Departamento.value_counts().head(8).to_dict())
print("alt:", m.Altitud.min(), m.Altitud.mean().round(1), m.Altitud.max())
print("lon:", m.LONGITUD.min(), m.LONGITUD.max(), "lat:", m.LATITUD.min(), m.LATITUD.max())
m.to_csv("/srv/mark02/analitica-final/aux/cne_estaciones_proyecto.csv", index=False)
